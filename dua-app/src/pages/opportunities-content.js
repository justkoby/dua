export function getOpportunityPathway(id) {
  const clean = String(id || '').replace(/^\/+|\/+$/g, '');
  if (clean === 'internship' || clean === 'remote-internship-programme-rip') return internshipProgramme;
  if (clean === 'fellowships') return internshipProgramme;
  if (clean === 'calls-for-papers') return opportunityPathways[2];
  if (clean === 'volunteer-opportunities') return opportunityPathways[3];
  if (clean === 'enterprise-week' || clean === 'foreign-africa-enterprise-week-few-2') return opportunityPathways[1];
  return [...opportunityPathways, internshipProgramme].find(item => item.id === clean) || opportunityPathways[0];
}

export function enquiryHref(item) {
  return `mailto:info@democratunionofafrica.org?subject=${encodeURIComponent(item.subject)}`;
}

